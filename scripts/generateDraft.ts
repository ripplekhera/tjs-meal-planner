#!/usr/bin/env tsx

/**
 * Generates a week with Claude and writes it as a draft to data/mealplans/ without
 * touching the database. Review it, then publish with `npm run meal-plan -- publish <file>`.
 *
 * Usage:
 *   npm run meal-plan:generate-draft -- [YYYY-MM-DD] [--rules rules.json] [--attempts 3] [--force]
 *
 * The date is any day in the target week (default: next week). --rules takes a JSON file
 * shaped like GenerationRules in lib/generation/rules.ts. Needs ANTHROPIC_API_KEY; uses
 * DATABASE_URL for recent-week history when it's reachable.
 */

import fs from "fs";
import path from "path";
import { closePool } from "@/lib/db";
import { loadPlanningGuides, loadRecentHistory } from "@/lib/generation/context";
import { GENERATION_MODEL, RecentHistory, generateWeek } from "@/lib/generation/generate";
import { normalizeRules } from "@/lib/generation/rules";
import { formatWeekRange, getWeekStartDateOnly, parseDateOnly } from "@/lib/weekRange";

const MEALPLANS_DIR = path.join(process.cwd(), "data", "mealplans");

function parseArgs(argv: string[]) {
  const args = { date: undefined as string | undefined, rulesPath: undefined as string | undefined, attempts: 3, force: false };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--rules") args.rulesPath = argv[++i];
    else if (arg === "--attempts") args.attempts = Number(argv[++i]);
    else if (arg === "--force") args.force = true;
    else if (!arg.startsWith("--")) args.date = arg;
    else throw new Error(`Unknown option: ${arg}`);
  }
  if (!Number.isInteger(args.attempts) || args.attempts < 1) {
    throw new Error("--attempts must be a positive whole number.");
  }
  return args;
}

function resolveWeekStart(date: string | undefined): string {
  if (!date) {
    const nextWeek = new Date();
    nextWeek.setDate(nextWeek.getDate() + 7);
    return getWeekStartDateOnly(nextWeek);
  }
  const parsed = parseDateOnly(date);
  if (!parsed) throw new Error(`Expected a date in YYYY-MM-DD format, got "${date}".`);
  return getWeekStartDateOnly(parsed);
}

async function loadHistoryOrNothing(weekStart: string): Promise<RecentHistory> {
  try {
    return await loadRecentHistory(weekStart);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.log(`⚠️  Couldn't read recent weeks from the database (${message}). Generating without history.`);
    return { meals: [], junkItems: [] };
  }
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const weekStart = resolveWeekStart(args.date);
  const weekRange = formatWeekRange(weekStart);
  const filepath = path.join(MEALPLANS_DIR, `mealplan-week-${weekStart}.md`);

  if (fs.existsSync(filepath) && !args.force) {
    throw new Error(`${path.relative(process.cwd(), filepath)} already exists. Pass --force to overwrite it.`);
  }

  const rules = normalizeRules(
    args.rulesPath ? JSON.parse(fs.readFileSync(args.rulesPath, "utf8")) : undefined
  );
  const [guides, history] = await Promise.all([loadPlanningGuides(), loadHistoryOrNothing(weekStart)]);

  console.log(`🍃 Generating ${weekRange} with ${GENERATION_MODEL} (up to ${args.attempts} attempts)...`);
  const result = await generateWeek({ weekRange, rules, guides, history, maxAttempts: args.attempts });

  const markdown = `# Week Plan: ${weekRange}

Generated by Claude (${GENERATION_MODEL}) on ${new Date().toISOString().slice(0, 10)} in ${result.attempts} attempt(s). Review it, then publish with \`npm run meal-plan -- publish ${path.relative(process.cwd(), filepath)}\`.

## Canonical JSON
\`\`\`json
${JSON.stringify(result.weekData, null, 2)}
\`\`\`
`;
  fs.mkdirSync(MEALPLANS_DIR, { recursive: true });
  fs.writeFileSync(filepath, markdown);

  for (const warning of result.warnings) console.log(`⚠️  ${warning}`);
  for (const error of result.errors) console.log(`❌ ${error}`);
  console.log(
    result.valid
      ? `✅ Wrote ${path.relative(process.cwd(), filepath)}`
      : `❌ Wrote ${path.relative(process.cwd(), filepath)}, but it still fails the checks above. Fix it by hand before publishing.`
  );
  if (!result.valid) process.exitCode = 1;
}

main()
  .catch((error) => {
    console.error("❌ Draft generation failed");
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await closePool();
  });
